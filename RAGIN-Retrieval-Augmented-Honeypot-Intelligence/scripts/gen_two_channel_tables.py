"""Generate §VI two-channel LaTeX tables from declared-channel artifacts.

Tables (paper §VI):
  1. two-channel metrics for the current-model ragin_full config: served-text
     is shown BOTH raw (echo-crediting rubric, the historical numbers) and
     echo-guarded (post-audit scorer; guarded means from the audit artifact's
     correction block, valid for this surface because the audit proved
     row-identity by pre-guard score equality on all 218 rows) vs CTI-analysis
     per suite
  2. external-baseline ladder under the DECLARED served-text channel
     (results/external_baseline_model_coherent.json) — levels are pre-guard
     and labeled as such; paired per-row deltas are scorer-invariant because
     the compared arms serve byte-identical strings on the decisive rows
  3. manual audit summary (results/cti_manual_audit.json): annotator
     agreement, strict P/R/F1, adjudication, and machine-vs-human agreement
     before/after the echo guard

Writes results/section_vi_two_channel_tables.tex.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
TC = ROOT / "results" / "two_channel_metrics.json"
MC = ROOT / "results" / "external_baseline_model_coherent.json"
AUDIT = ROOT / "results" / "cti_manual_audit.json"
OUT = ROOT / "results" / "section_vi_two_channel_tables.tex"
# Sync copy into the paper tree so the manuscript build is self-contained
# and regeneration stays a single command.
PAPER_TEX = ROOT.parent / "paper" / "tdsc" / "sections" / "two_channel_tables.tex"

SUITE_LABELS = {
    "cti_technique": "Technique identification (123 q)",
    "cti_actor": "Actor attribution (35 q)",
    "deception": "Persona realism (60 q)",
}
SUITE_SHORT = {
    "cti_technique": "Technique identification",
    "cti_actor": "Actor attribution",
    "deception": "Persona realism",
}


def _fmt(v: Any) -> str:
    return "--" if v is None else f"{v:.3f}"


def main() -> int:
    tc = json.loads(TC.read_text())
    mc = json.loads(MC.read_text())
    audit = json.loads(AUDIT.read_text())

    arms = mc["model_coherent_table"]["arms"]
    ladder_rows = [
        ("Vanilla Cowrie (no LLM)", "cowrie"),
        ("Stateful LLM (HoneyGPT/LLM-SSHH)", "stateful_llm"),
        ("Bare LLM (unverified)", "llm_unverified"),
        ("RAGIN w/o verifier", "rag_no_verifier_repro"),
        ("RAGIN full (verified loop)", "ragin_full"),
        ("RAGIN full + host fiction", "ragin_hostfiction"),
    ]

    gen = tc["config"]["generator_model"]
    gen_label = gen if "deepseek" in str(gen) else "gateway default (glm-5.3-flash-free)"

    row_id = audit["served_text_row_identity_vs_two_channel"]
    egc = audit["echo_guard_correction"]
    guarded_served: dict[str, Any] = dict(egc["post_correction_served_avg"])
    pre_guard: dict[str, Any] = egc["pre_correction"]["served_avg"]
    post_guard: dict[str, Any] = egc["post_correction_served_avg"]

    lines: list[str] = []
    lines.append("% Auto-generated by scripts/gen_two_channel_tables.py — 2026-09-28")
    lines.append("% Declared scoring channels (never mix without labeling):")
    lines.append("%   served_text  = deception realism (what the attacker receives)")
    lines.append("%   cti_analysis = intelligence value (Don extraction; NOT served)")
    lines.append("% Served-text numbers are echo-guarded (blinded-audit correction,")
    lines.append("%   results/cti_manual_audit.json); the audited surface was proven")
    lines.append("%   row-identical to the two-channel reference run "
                 f"({row_id['identical_pre_guard']}/{row_id['rows_compared']}"
                 " pre-guard score equality).")
    lines.append("")
    lines.append("\\subsection{Two-Channel Evaluation}")
    lines.append("")
    lines.append(
        "Every metric below declares its \\emph{scoring channel}. The "
        "\\textbf{served-text} channel scores what the attacker actually receives; "
        "the \\textbf{CTI-analysis} channel scores what the pipeline identified "
        "(Don extraction), which is never shown to the attacker. The two answer "
        "different questions---deception realism vs.\\ intelligence "
        "value---and are never combined into a single composite."
    )
    lines.append("")
    lines.append(
        "The served-text rubric originally credited a technique identifier or "
        "actor name appearing anywhere in the response. A double-annotated "
        "blinded audit (\\S\\ref{sec:scorer-audit}) found that on "
        "fallback-heavy runs the served surface is dominated by deterministic "
        "templates that echo the query verbatim, so the raw rubric credited "
        "error text (97 of 218 rows corrected). Both raw and guarded columns "
        "are shown: the gap itself is a finding about the serve surface."
    )
    lines.append("")

    # ── Table 1: two-channel, raw vs guarded ──
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Two-channel metrics of the verified RAGIN pipeline"
                 f" (generator: {gen_label}). Served text is shown raw (the"
                 " echo-crediting rubric) and echo-guarded (post-audit); the"
                 " guarded column is canonical. The deception surface"
                 " deliberately answers CTI-style questions with machine"
                 " transcripts, not technique essays; the intelligence value"
                 " lives in the analysis channel. Guarded numbers are computed"
                 " on the audited surface, proven row-identical to this run by"
                 " pre-guard score equality on all 218 rows"
                 " (\\texttt{cti\\_manual\\_audit.json}).}")
    lines.append("\\label{tab:two-channel}")
    lines.append("\\begin{tabular}{lccc}")
    lines.append("\\toprule")
    lines.append("Suite & Served (raw) & Served (guarded) & CTI analysis \\\\")
    lines.append("\\midrule")
    for suite, label in SUITE_LABELS.items():
        raw = tc["by_suite"][suite]["served_text_avg"]
        g = guarded_served.get(suite)
        ca = tc["by_suite"][suite]["cti_analysis_avg"]
        lines.append(
            f"{label} & {_fmt(raw)} & {_fmt(g)} & {_fmt(ca)} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    # ── Table 2: ladder (levels pre-guard, deltas scorer-invariant) ──
    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{External baselines on the 218-query workload"
                 " (generator: deepseek-v4-flash-free for all LLM arms)."
                 " \\textbf{All scores are served-text channel under the raw"
                 " (pre-guard) rubric}---the deception quality an attacker"
                 " experiences. Paired per-row deltas are scorer-invariant:"
                 " the verified loop serves byte-identical strings to the"
                 " no-verifier arm on all 218 rows (paired delta 0.000), and"
                 " the host-fiction layer adds cross-session consistency at"
                 " exactly zero quality cost (paired per-row delta 0.000)."
                 " Absolute levels on fallback-heavy runs shift under the"
                 " echo guard (Table~\\ref{tab:two-channel}); the grounding"
                 " and consistency contrasts do not.}")
    lines.append("\\label{tab:baseline-served-text}")
    lines.append("\\begin{tabular}{lc}")
    lines.append("\\toprule")
    lines.append("Arm & Served-text composite \\\\")
    lines.append("\\midrule")
    for label, key in ladder_rows:
        arm = arms[key]
        comp = arm.get("composite")
        lines.append(f"{label} & {_fmt(comp)} \\\\")
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")

    # ── Table 3: manual audit summary ──
    ps = audit["per_suite"]
    mvh = audit["machine_vs_human"]
    pre_mvh = egc["pre_correction"]["machine_vs_human"]
    adj = audit["adjudication_summary"]

    def _f1(suite: str, slot: str) -> str:
        prf = ps[suite].get(f"prf_{slot}")
        return "--" if not prf else _fmt(prf["strict"]["f1"])

    def _adj(suite: str) -> str:
        a = adj[suite]
        return f"{a['C_sides_with_A']}/{a['C_sides_with_B']}/{a['C_neither']}"

    lines.append("\\begin{table}[t]")
    lines.append("\\centering")
    lines.append("\\caption{Blinded annotator audit of the automated scorers"
                 " (\\S\\ref{sec:scorer-audit}): two independent blinded"
                 " annotators (fixed-identity free-tier models, no gold"
                 " labels, no pipeline scores), third-annotator adjudication,"
                 " taxonomy pinned to \\\\attck{} Enterprise v19.1 (vendored"
                 " STIX, sha256-locked). Scorer-vs-annotator agreement is Cohen's"
                 " $\\kappa$ between the automated channel verdicts and the"
                 " adjudicated annotator labels, before/after the echo guard. All"
                 " disagreements were adjudicated; none unresolved.}")
    lines.append("\\label{tab:cti-audit}")
    lines.append("\\small")
    lines.append("\\setlength{\\tabcolsep}{3.5pt}")
    lines.append("\\begin{tabular}{@{}lccccc@{}}")
    lines.append("\\toprule")
    lines.append("Suite & $n$ & $\\kappa$ (A,B) & strict F1 (A/B) & adjud.\\ A/B/neither"
                 " & scorer-vs-annot.\\ $\\kappa$ pre$\\to$post \\\\")
    lines.append("\\midrule")
    for suite in ("cti_technique", "cti_actor", "deception"):
        s = ps[suite]
        k = s["kappa_A_vs_B"]
        kval = k.get("identification") or k.get("realism")
        kn = s["kappa_pair_n"]
        lines.append(
            f"{SUITE_SHORT[suite]} & {s['n_rows']} & {_fmt(kval)} ($n$={kn}) & "
            f"{_f1(suite, 'A')}/{_f1(suite, 'B')} & {_adj(suite)} & "
            f"{_fmt(pre_mvh[suite]['kappa'])}$\\to${_fmt(mvh[suite]['kappa'])} \\\\"
        )
    lines.append("\\bottomrule")
    lines.append("\\end{tabular}")
    lines.append("\\end{table}")
    lines.append("")
    lines.append(
        "% Echo-guard correction provenance: results/cti_manual_audit.json"
        f" (echo_guard_correction): {egc['rows_changed']} rows changed;"
        f" served avg pre->post: technique {pre_guard['cti_technique']}->"
        f"{post_guard['cti_technique']}, actor {pre_guard['cti_actor']}->"
        f"{post_guard['cti_actor']}, deception {pre_guard['deception']}->"
        f"{post_guard['deception']} (persona scorer already penalized echoes)."
        " Post-guard scorer-vs-annotator kappa: technique -0.187->+0.349,"
        " actor 0.048->0.914 (scorer now agrees with the annotator models)."
        " Ladder paired per-row deltas are scorer-invariant (byte-identical"
        " served strings across compared arms on the decisive rows)."
    )
    lines.append("")
    lines.append(
        "% Historical note (Sep-22 campaign): its official technique (0.960) and"
        " actor (0.850) averages were BOTH-channel (served text max analysis)."
        " Its served-text-only equivalents are 0.493 / 0.666 under the raw"
        " rubric. Do not compare across channels; see"
        " results/technique_rubric_diff_investigation.json."
    )

    tex = "\n".join(lines) + "\n"
    OUT.write_text(tex)
    if PAPER_TEX.parent.exists():
        PAPER_TEX.write_text(tex)
        print(f"paper copy: {PAPER_TEX}")
    print(f"tables written: {OUT}")
    print("\n--- preview ---")
    print("\n".join(lines[:44]))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
